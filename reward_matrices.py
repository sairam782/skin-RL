def get_reward_matrix(matrix_id=1):
    """Return a reward matrix by id from 1 to 25."""
    try:
        return REWARD_MATRICES[int(matrix_id)]
    except (KeyError, ValueError) as exc:
        valid_ids = ", ".join(str(i) for i in sorted(REWARD_MATRICES))
        raise ValueError(f"Unknown reward matrix '{matrix_id}'. Valid ids: {valid_ids}") from exc


def list_reward_matrices():
    """Return matrix id/name pairs for display in CLIs or notebooks."""
    return [(matrix_id, REWARD_MATRIX_NAMES[matrix_id]) for matrix_id in sorted(REWARD_MATRICES)]
